import { MayaMathV1 } from '../modules/maya/MayaMathV1';

export type MayanColor = 'Rojo' | 'Blanco' | 'Azul' | 'Amarillo';

export function getMayanColorByNawal(kicheName?: string | null): MayanColor | undefined {
    if (!kicheName) return undefined;

    const candidates = [
        kicheName,
        kicheName === "I'x" ? 'Ix' : null,
        kicheName === 'Ix' ? "I'x" : null
    ].filter(Boolean) as string[];

    let index = -1;
    for (const candidate of candidates) {
        index = NAWALES.findIndex((n: any) => n.name === candidate);
        if (index >= 0) break;
    }

    if (index < 0) return undefined;

    const colors: MayanColor[] = ['Rojo', 'Blanco', 'Azul', 'Amarillo'];
    return colors[(index + 2) % 4];
}

export class MayanCalculator {
    static calculate(dateString: string, lang: 'es' | 'en' = 'es') {
        
        // Use canonical math authority for all runtime consumers
        const mathResult = MayaMathV1.calculate({ localDate: dateString });
        const tone = mathResult.tone;
        
        // Map canonical key to legacy dictionary spelling if needed (I'x -> Ix)
        const legacyKey = mathResult.canonicalNawalKey === "I'x" ? "Ix" : mathResult.canonicalNawalKey;
        
        const nawalData = NAWALES.find(n => n.name === legacyKey) || NAWALES[0];
        const toneData = TONES[lang][tone - 1];

        const meaning = nawalData.meaning[lang] || nawalData.meaning.es;
        const description = nawalData.description[lang] || nawalData.description.es;
        const shortDescription = description.split('.')[0];
        
        const mission = lang === 'es' 
            ? `Misión de ${nawalData.name}: ${meaning}. Expandir la conciencia a través de ${shortDescription}.`
            : `Mission of ${nawalData.name}: ${meaning}. Expand consciousness through ${shortDescription}.`;
            
        const challenges = lang === 'es'
            ? `Desafío: Integrar la sombra de ${nawalData.name} y usar su energía para construir, no para destruir.`
            : `Challenge: Integrate the shadow of ${nawalData.name} and use its energy to build, not destroy.`;

        return {
            kicheName: nawalData.name,
            tone: tone,
            meaning: meaning,
            toneName: toneData,
            description: description,
            mission: mission,
            challenges: challenges,
            glyphUrl: `/nawales/${nawalData.name.toLowerCase().replace(/'/g, "")}.svg`
        };
    }
}
